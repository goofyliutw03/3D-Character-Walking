import assert from 'node:assert/strict';
import { test } from 'node:test';
import { BoxGeometry, Group, Mesh, MeshStandardMaterial, ShaderLib } from 'three';
import { EnvironmentScan } from '../src/engine/EnvironmentScan.ts';

test('environment scan composes existing hooks and follows deformed world positions', () => {
  const environment = new Group();
  const geometry = new BoxGeometry();
  const material = new MeshStandardMaterial();
  const compile = shader => {
    shader.vertexShader = shader.vertexShader.replace('#include <begin_vertex>',
      '#include <begin_vertex>\ntransformed.y += 2.0;');
  };
  material.onBeforeCompile = compile;
  const cacheKey = material.customProgramCacheKey;
  const originalKey = cacheKey.call(material);
  environment.add(new Mesh(geometry, material));
  const scan = new EnvironmentScan();
  scan.prepare(environment);
  const preparedCompile = material.onBeforeCompile;
  const preparedKey = material.customProgramCacheKey();
  const preparedVersion = material.version;
  const shader = { ...ShaderLib.standard, uniforms: {} };
  material.onBeforeCompile(shader);
  assert.match(shader.vertexShader, /transformed\.y \+= 2\.0/);
  assert.match(shader.vertexShader, /displacementmap_vertex>[\s\S]*project_vertex>[\s\S]*modelMatrix \* scanPosition/);
  assert.match(shader.fragmentShader, /scanFront[\s\S]*scanTail/);
  const uniforms = shader.uniforms;
  assert.equal(uniforms.environmentScanStrength.value, 0);
  const foot = { x: 1, y: 2, z: 3 };
  scan.start(foot);
  foot.x = 5;
  scan.update(100);
  scan.update(1100);
  assert.deepEqual(uniforms.environmentScanOrigin.value.toArray(), [1, 2, 3]);
  assert.equal(uniforms.environmentScanWave.value, 10);
  assert.deepEqual(uniforms.environmentScanSquaredBand.value.toArray(), [(10 - 3.4) ** 2, (10 + 0.16) ** 2]);
  assert.match(shader.fragmentShader, /if \(scanDistanceSquared[\s\S]*sqrt\(scanDistanceSquared\)/);
  assert.notEqual(material.customProgramCacheKey(), originalKey);
  scan.start(foot);
  scan.update(1150);
  assert.deepEqual(uniforms.environmentScanOrigin.value.toArray(), [5, 2, 3]);
  assert.equal(uniforms.environmentScanWave.value, 0);
  scan.update(3275);
  assert.equal(uniforms.environmentScanWave.value, 20);
  assert.equal(uniforms.environmentScanStrength.value, 0.5);
  scan.update(3400);
  assert.equal(uniforms.environmentScanStrength.value, 0);
  assert.equal(material.onBeforeCompile, preparedCompile);
  assert.equal(material.customProgramCacheKey(), preparedKey);
  assert.equal(material.version, preparedVersion);
  geometry.dispose();
  material.dispose();
});

test('scan watches secondary actor roots and prepares hidden LODs and late assets once', () => {
  const geometry = new BoxGeometry();
  const targetMaterial = new MeshStandardMaterial();
  const trafficMaterial = new MeshStandardMaterial();
  const target = new Group();
  const traffic = new Group();
  const car = new Mesh(geometry, trafficMaterial);
  const scan = new EnvironmentScan();
  const originalTarget = targetMaterial.onBeforeCompile;
  const originalTraffic = trafficMaterial.onBeforeCompile;
  traffic.add(car);
  car.visible = false;
  scan.watch(target);
  scan.watch(traffic);
  assert.notEqual(trafficMaterial.onBeforeCompile, originalTraffic);
  target.add(new Mesh(geometry, targetMaterial));
  assert.notEqual(targetMaterial.onBeforeCompile, originalTarget);
  const prepared = targetMaterial.onBeforeCompile;
  target.add(new Mesh(geometry, targetMaterial));
  assert.equal(targetMaterial.onBeforeCompile, prepared);
  scan.dispose();
  const late = new MeshStandardMaterial();
  const originalLate = late.onBeforeCompile;
  target.add(new Mesh(geometry, late));
  assert.equal(late.onBeforeCompile, originalLate);
  late.dispose();
  geometry.dispose();
  targetMaterial.dispose();
  trafficMaterial.dispose();
});
